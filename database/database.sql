-- =========================================================
-- DALAREICH POS & INVENTORY SYSTEM
-- COMPLETE DATABASE RESET
-- SUPABASE POSTGRESQL
-- =========================================================

-- =========================================================
-- WARNING
-- =========================================================
-- THIS SCRIPT DELETES THE EXISTING TABLES AND THEIR DATA.
--
-- Run this only when you want to completely reset
-- the Dalareich POS database.
--
-- This script is intended for:
-- Supabase PostgreSQL
-- =========================================================


-- =========================================================
-- 1. REMOVE EXISTING TRIGGERS / FUNCTIONS
-- =========================================================

DROP FUNCTION IF EXISTS update_updated_at_column() CASCADE;


-- =========================================================
-- 2. REMOVE EXISTING TABLES
-- =========================================================

DROP TABLE IF EXISTS sale_items CASCADE;

DROP TABLE IF EXISTS sales CASCADE;

DROP TABLE IF EXISTS products CASCADE;

DROP TABLE IF EXISTS suppliers CASCADE;

DROP TABLE IF EXISTS customers CASCADE;

DROP TABLE IF EXISTS users CASCADE;


-- =========================================================
-- 3. USERS TABLE
-- =========================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    full_name TEXT NOT NULL,

    username TEXT NOT NULL UNIQUE,

    password_hash TEXT NOT NULL,

    role TEXT NOT NULL
        CHECK (
            role IN (
                'Administrator',
                'Staff',
                'Manager'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 4. CUSTOMERS TABLE
-- =========================================================

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_code TEXT NOT NULL UNIQUE,

    full_name TEXT NOT NULL,

    customer_type TEXT NOT NULL
        CHECK (
            customer_type IN (
                'Individual',
                'Wholesale',
                'Institutional'
            )
        ),

    phone TEXT,

    email TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 5. SUPPLIERS TABLE
-- =========================================================

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    supplier_code TEXT NOT NULL UNIQUE,

    supplier_name TEXT NOT NULL,

    contact_person TEXT,

    phone TEXT,

    email TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 6. PRODUCTS TABLE
-- =========================================================

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_code TEXT NOT NULL UNIQUE,

    product_name TEXT NOT NULL,

    category TEXT NOT NULL,

    price NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (price >= 0),

    stock_quantity INTEGER NOT NULL DEFAULT 0
        CHECK (stock_quantity >= 0),

    reorder_level INTEGER NOT NULL DEFAULT 0
        CHECK (reorder_level >= 0),

    unit TEXT NOT NULL DEFAULT 'unit',

    batch_number TEXT,

    expiration_date DATE,

    supplier_id BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT products_supplier_fk
        FOREIGN KEY (supplier_id)
        REFERENCES suppliers(id)
        ON DELETE SET NULL
);


-- =========================================================
-- 7. SALES TABLE
-- =========================================================

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_number TEXT NOT NULL UNIQUE,

    user_id BIGINT,

    customer_id BIGINT,

    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (subtotal >= 0),

    tax_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (tax_amount >= 0),

    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (total_amount >= 0),

    payment_method TEXT NOT NULL DEFAULT 'Cash',

    sale_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT sales_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE SET NULL,

    CONSTRAINT sales_customer_fk
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
        ON DELETE SET NULL
);


-- =========================================================
-- 8. SALE ITEMS TABLE
-- =========================================================

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_id BIGINT NOT NULL,

    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL
        CHECK (quantity > 0),

    price NUMERIC(12, 2) NOT NULL
        CHECK (price >= 0),

    subtotal NUMERIC(12, 2) NOT NULL
        CHECK (subtotal >= 0),

    CONSTRAINT sale_items_sale_fk
        FOREIGN KEY (sale_id)
        REFERENCES sales(id)
        ON DELETE CASCADE,

    CONSTRAINT sale_items_product_fk
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT
);


-- =========================================================
-- 9. INDEXES
-- =========================================================

-- PRODUCTS

CREATE INDEX idx_products_stock
    ON products(stock_quantity, reorder_level);

CREATE INDEX idx_products_supplier
    ON products(supplier_id);


-- SALES

CREATE INDEX idx_sales_date
    ON sales(sale_date);

CREATE INDEX idx_sales_user
    ON sales(user_id);

CREATE INDEX idx_sales_customer
    ON sales(customer_id);


-- SALE ITEMS

CREATE INDEX idx_sale_items_sale
    ON sale_items(sale_id);

CREATE INDEX idx_sale_items_product
    ON sale_items(product_id);


-- =========================================================
-- 10. UPDATED_AT FUNCTION
-- =========================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    NEW.updated_at = NOW();

    RETURN NEW;

END;
$$;


-- =========================================================
-- 11. PRODUCTS UPDATED_AT TRIGGER
-- =========================================================

CREATE TRIGGER products_updated_at
BEFORE UPDATE ON products
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();


-- =========================================================
-- 12. VERIFY TABLES
-- =========================================================

SELECT
    table_name
FROM information_schema.tables
WHERE table_schema = 'public'
AND table_name IN (
    'users',
    'customers',
    'suppliers',
    'products',
    'sales',
    'sale_items'
)
ORDER BY table_name;


-- =========================================================
-- 13. VERIFY TABLE COLUMNS
-- =========================================================

SELECT
    table_name,
    ordinal_position,
    column_name,
    data_type,
    is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
AND table_name IN (
    'users',
    'customers',
    'suppliers',
    'products',
    'sales',
    'sale_items'
)
ORDER BY
    table_name,
    ordinal_position;


-- =========================================================
-- 14. VERIFY FOREIGN KEYS
-- =========================================================

SELECT
    tc.table_name,
    kcu.column_name,
    ccu.table_name AS referenced_table,
    ccu.column_name AS referenced_column
FROM information_schema.table_constraints AS tc

JOIN information_schema.key_column_usage AS kcu
    ON tc.constraint_name = kcu.constraint_name
    AND tc.table_schema = kcu.table_schema

JOIN information_schema.constraint_column_usage AS ccu
    ON ccu.constraint_name = tc.constraint_name
    AND ccu.table_schema = tc.table_schema

WHERE tc.constraint_type = 'FOREIGN KEY'
AND tc.table_schema = 'public'

ORDER BY
    tc.table_name,
    kcu.column_name;


